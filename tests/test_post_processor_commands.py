class TestExtractAudioCommands:
    """Verify ffmpeg commands for audio extraction."""

    def test_extract_audio_mp3_command(self, pp, mock_popen):
        """MP3 extraction uses libmp3lame codec and -vn flag."""
        pp.extract_audio("/tmp/video.mp4", format="mp3")

        args = mock_popen.call_args[0][0]
        assert args[0] == "/usr/bin/ffmpeg"
        assert "-i" in args
        assert "/tmp/video.mp4" in args
        assert "-vn" in args  # No video
        assert "-acodec" in args
        assert "libmp3lame" in args

    def test_extract_audio_aac_command(self, pp, mock_popen):
        """AAC extraction uses aac codec."""
        pp.extract_audio("/tmp/video.mp4", format="m4a")

        args = mock_popen.call_args[0][0]
        assert "-acodec" in args
        assert "aac" in args
        # Output should have .m4a extension
        output_path = args[-1]
        assert output_path.endswith(".m4a")

    def test_extract_audio_wav_command(self, pp, mock_popen):
        """WAV extraction uses pcm_s16le codec."""
        pp.extract_audio("/tmp/video.mp4", format="wav")

        args = mock_popen.call_args[0][0]
        assert "pcm_s16le" in args
        output_path = args[-1]
