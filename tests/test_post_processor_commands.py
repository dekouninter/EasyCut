class TestFFmpegExecution:
    """Test FFmpeg execution behavior."""

    def test_ffmpeg_failure_returns_none(self, pp):
        """Failed FFmpeg execution returns None."""
        with patch("subprocess.Popen") as mock_popen:
            mock_process = MagicMock()
            mock_process.returncode = 1
            mock_process.communicate.return_value = (b"", b"Error occurred")
            mock_popen.return_value = mock_process

            result = pp.extract_audio("/tmp/video.mp4")
        assert result is None

    def test_ffmpeg_exception_returns_none(self, pp):
        """FFmpeg exception returns None and doesn't crash."""
        with patch("subprocess.Popen") as mock_popen:
            mock_popen.side_effect = OSError("FFmpeg not found")

            result = pp.extract_audio("/tmp/video.mp4")
        assert result is None

    def test_callback_called_on_success(self, pp, mock_popen):
        """Callback is invoked with True on success."""
        callback = MagicMock()
        pp.extract_audio("/tmp/video.mp4", callback=callback)

        callback.assert_called_once_with(True)

    def test_callback_called_on_failure(self, pp):
        """Callback is invoked with False on failure."""
        with patch("subprocess.Popen") as mock_popen:
            mock_process = MagicMock()
            mock_process.returncode = 1
            mock_process.communicate.return_value = (b"", b"Error")
            mock_popen.return_value = mock_process

            callback = MagicMock()
            pp.extract_audio("/tmp/video.mp4", callback=callback)

        callback.assert_called_once_with(False)

    def test_overwrite_flag_present(self, pp, mock_popen):
        """All operations include -y for overwrite without prompting."""
        pp.compress("/tmp/video.mp4")
        args = mock_popen.call_args[0][0]
        assert "-y" in args

        mock_popen.reset_mock()
        pp.denoise_video("/tmp/video.mp4")
        args = mock_popen.call_args[0][0]
        assert "-y" in args


