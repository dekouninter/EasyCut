class TestGetMediaInfo:
    """Test media info retrieval via ffprobe."""

    def test_get_media_info_success(self, pp):
        """Successful ffprobe returns parsed JSON."""
        mock_output = '{"format": {"filename": "test.mp4"}, "streams": []}'
        with patch("subprocess.run") as mock_run:
            mock_run.return_value = MagicMock(
                returncode=0,
                stdout=mock_output
            )
            result = pp.get_media_info("/tmp/test.mp4")

        assert result == {"format": {"filename": "test.mp4"}, "streams": []}

    def test_get_media_info_failure_returns_empty(self, pp):
        """Failed ffprobe returns empty dict."""
        with patch("subprocess.run") as mock_run:
            mock_run.return_value = MagicMock(returncode=1, stdout="")
            result = pp.get_media_info("/tmp/test.mp4")

        assert result == {}

    def test_get_media_info_exception_returns_empty(self, pp):
        """ffprobe exception returns empty dict."""
        with patch("subprocess.run") as mock_run:
            mock_run.side_effect = subprocess.TimeoutExpired("ffprobe", 30)
            result = pp.get_media_info("/tmp/test.mp4")

        assert result == {}
